// The About page has a fixed structure: these eight sections, in this order.
// Admins edit each section's title and text and show or hide it; they can't
// add, remove or reorder sections (that's deliberate — no page builder).
//
// DEFAULT_SECTIONS is the starting content. The same text is seeded into the
// database by supabase/migrations/0007_about.sql; the site also falls back to
// it when the database can't be read, so the page is never blank.

export const ABOUT_SECTION_KEYS = [
  "intro",
  "origin",
  "principles",
  "team",
  "how",
  "editorial",
  "funding",
  "join",
] as const;

export type AboutSectionKey = (typeof ABOUT_SECTION_KEYS)[number];

export type AboutSection = {
  key: AboutSectionKey;
  title_ar: string;
  body_ar: string;
  /** Only used by the «join» call-to-action section. */
  link_label_ar: string | null;
  link_url: string | null;
  is_published: boolean;
};

export function isAboutSectionKey(v: string): v is AboutSectionKey {
  return (ABOUT_SECTION_KEYS as readonly string[]).includes(v);
}

