function Icon({ platform, className }: { platform: SocialPlatform; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} fill="currentColor" aria-hidden="true">
      <path d={ICON_PATHS[platform]} />
    </svg>
  );
}

/** Renders only the platforms that have a real URL configured in src/lib/social.ts. */
export function SocialLinks({ className }: { className?: string }) {
  const links = SOCIAL_LINKS.filter(
    (s): s is typeof s & { url: string } => !!s.url,
  );
  if (!links.length) return null;

  return (
    <ul className={cn("flex items-center gap-3", className)}>
      {links.map((s) => (
        <li key={s.platform}>
          <a
            href={s.url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={s.label}
            className="flex size-8 items-center justify-center rounded-full text-current/70 transition-colors hover:text-current"
          >
            <Icon platform={s.platform} className="size-[1.05rem]" />
          </a>
        </li>
      ))}
    </ul>
  );
}
